"""Markdown report with an explicit validation status (AI draft -> validated)."""
from datetime import datetime

STATUS_DRAFT = "AI DRAFT - not yet validated by a human"


def _scope_fallback(scope: dict) -> str:
    used = [f"{k}={v}" for k, v in scope.items() if v]
    return ", ".join(used) if used else "all data"


def render_markdown(name: str, payload: dict, summary: str, root_cause: str, check: dict,
                    provider: str, status: str = STATUS_DRAFT, validation: dict | None = None) -> str:
    meta = payload.get("meta", {})
    lines = [f"# Executive Summary - {name}", "",
             f"**Status: {status}**", "",
             f"- Scope: {meta.get('scope_text') or _scope_fallback(meta.get('scope', {}))}",
             f"- Source: {meta.get('report', '')}",
             f"- Text generated by: {provider}" + (" (offline template, no language model)" if provider == "mock" else ""),
             f"- Generated on: {datetime.now():%Y-%m-%d %H:%M}", "",
             "## Executive summary", "", summary, "",
             "## Anomalies explained (contributing factors, not proven causes)", "", root_cause, "",
             "## Automatic number check", ""]
    if check is None:
        lines.append("Not applicable (no data).")
    elif check["ok"]:
        lines.append(f"All {check['numbers_checked']} figures found in the JSON input.")
    else:
        lines.append(f"WARNING: {len(check['ungrounded'])} figure(s) not found in the JSON input "
                     f"(out of {check['numbers_checked']} checked): "
                     + ", ".join(f"`{u['text']}`" for u in check["ungrounded"]))
    lines += ["", "## Human validation", ""]
    if validation:
        lines += [f"- Reviewer: {validation['reviewer']}", f"- Date: {validation['date']}",
                  f"- Decision: {validation['decision']}", f"- Notes: {validation.get('notes') or '-'}"]
        for q, a in validation["checklist"].items():
            lines.append(f"- [{'x' if a else ' '}] {q}")
    else:
        lines.append("Pending. Run `python -m src.validate <this file> --reviewer \"Name\"` or use the Streamlit app.")
    return "\n".join(lines) + "\n"
